use std::error::Error;
use std::fs;
use std::path::Path;

use cuenote_lib::note_format::{
    AssetManifest, AssetManifestEntry, Block, Document, Inline, ListItem, Mark, MediaType,
    MindMapNode, NoteContent, Organization, PlainText, Sections, TableRow, TaskListItem,
    Timestamps,
};
use schemars::schema_for;
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn Error>> {
    let check_only = std::env::args().skip(1).any(|arg| arg == "--check");
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let outputs = [
        (
            root.join("schemas/document-v1.schema.json"),
            json_schema(&schema_for!(Document))?,
        ),
        (
            root.join("schemas/manifest-v1.schema.json"),
            json_schema(&schema_for!(AssetManifest))?,
        ),
        (
            root.join("src/generated/note-format.ts"),
            typescript_bindings(),
        ),
    ];

    let mut stale = Vec::new();
    for (path, contents) in outputs {
        if check_only {
            match fs::read_to_string(&path) {
                Ok(existing) if existing == contents => {}
                _ => stale.push(path),
            }
        } else {
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent)?;
            }
            fs::write(path, contents)?;
        }
    }
    if !stale.is_empty() {
        let paths = stale
            .iter()
            .map(|path| path.display().to_string())
            .collect::<Vec<_>>()
            .join("\n");
        return Err(format!("generated note format files are stale:\n{paths}").into());
    }
    Ok(())
}

fn json_schema(schema: &impl serde::Serialize) -> Result<String, serde_json::Error> {
    let mut contents = serde_json::to_string_pretty(schema)?;
    contents.push('\n');
    Ok(contents)
}

fn typescript_bindings() -> String {
    let config = Config::default();
    let mut contents = String::from(
        "// Generated by `cargo run --bin export_note_schema`. Do not edit by hand.\n\n",
    );
    push_decl(&mut contents, PlainText::decl(&config));
    push_decl(&mut contents, NoteContent::decl(&config));
    push_decl(&mut contents, Document::decl(&config));
    push_decl(&mut contents, Sections::decl(&config));
    push_decl(&mut contents, Organization::decl(&config));
    push_decl(&mut contents, Timestamps::decl(&config));
    push_decl(&mut contents, Block::decl(&config));
    push_decl(&mut contents, Inline::decl(&config));
    push_decl(&mut contents, Mark::decl(&config));
    push_decl(&mut contents, ListItem::decl(&config));
    push_decl(&mut contents, TaskListItem::decl(&config));
    push_decl(&mut contents, TableRow::decl(&config));
    push_decl(&mut contents, MindMapNode::decl(&config));
    push_decl(&mut contents, AssetManifest::decl(&config));
    push_decl(&mut contents, AssetManifestEntry::decl(&config));
    push_decl(&mut contents, MediaType::decl(&config));
    while contents.ends_with("\n\n") {
        contents.pop();
    }
    contents
}

fn push_decl(contents: &mut String, declaration: String) {
    contents.push_str("export ");
    contents.push_str(&declaration);
    contents.push_str("\n\n");
}
